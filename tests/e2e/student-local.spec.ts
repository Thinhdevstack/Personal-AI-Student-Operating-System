  await expect(page.getByText('Ollama đã kết nối · model đã có')).toBeVisible();
  const drop = async (name: string, bytes: Buffer) => {
    const transfer = await page.evaluateHandle(({ filename, data }) => {
      const value = new DataTransfer();
      value.items.add(new File([new Uint8Array(data)], filename, { type: 'application/pdf' }));
      return value;
    }, { filename: name, data: Array.from(bytes) });
    await page.locator('.student-dropzone').dispatchEvent('drop', { dataTransfer: transfer });
    await transfer.dispose();
  };
  await drop('invalid.txt', Buffer.from('invalid'));
  await expect(page.locator('.student-error')).toContainText('PDF');
  await drop('OOP.pdf', studentPdf(['Aggregation and composition describe object relationships in OOP.']));
  await expect(page.getByText('OOP.pdf', { exact: true })).toBeVisible();
  await expect.poll(async () => (await (await request.get(`/api/student/courses/${oop.id}/materials`)).json())[0]?.status).toBe('ready');
