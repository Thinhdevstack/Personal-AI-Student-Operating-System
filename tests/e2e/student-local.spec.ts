  context.on('request', (req) => { if (/https:\/\/(?:api\.openai\.com|generativelanguage\.googleapis\.com|api\.deepseek\.com)/.test(req.url())) external.push(req.url()); });
  const config = await (await request.get('/api/student/ai')).json();
  expect(config.isMock).toBe(false); expect(config.studentDemo).toBe(false);
  expect(config.defaultProvider).toBe('ollama'); expect(config.embedding.provider).toBe('ollama');
  expect(config.webSearch.configured).toBe(false);
