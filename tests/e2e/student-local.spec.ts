import { test, expect } from '@playwright/test';
import { studentPdf } from '../fixtures/student-pdf.mjs';
import { officeStartTimeout } from './browser-options';

test('@smoke local learning: PDF drop, scoped answers, expanded mode, cancel/retry, Office and mobile', async ({ page, request, context }) => {
  const errors: string[] = [], external: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  context.on('request', (req) => { if (/https:\/\/(?:api\.openai\.com|generativelanguage\.googleapis\.com|api\.deepseek\.com)/.test(req.url())) external.push(req.url()); });
  const config = await (await request.get('/api/student/ai')).json();
  expect(config.isMock).toBe(false); expect(config.studentDemo).toBe(false);
  expect(config.defaultProvider).toBe('ollama'); expect(config.embedding.provider).toBe('ollama');
  expect(config.webSearch.configured).toBe(false);
  expect((await request.post('/event', { data: {} })).status()).toBe(404);
  const semester = await (await request.post('/api/student/semesters', { data: { name: 'Local test', academicYear: '2026' } })).json();
  const oop = await (await request.post('/api/student/courses', { data: { semesterId: semester.id, name: 'Lập trình hướng đối tượng', code: 'OOP' } })).json();
  const db = await (await request.post('/api/student/courses', { data: { semesterId: semester.id, name: 'Cơ sở dữ liệu', code: 'DB' } })).json();
  await page.goto(`/student?course=${oop.id}&lang=vi`);
  await expect(page.locator('.student-demo-badge')).toHaveText('AI local · Ollama');
  await expect(page.getByText('Ollama đã kết nối · model đã có')).toBeVisible();
  const drop = async (name: string, bytes: Buffer) => {
    const transfer = await page.evaluateHandle(({ filename, data }) => {
      const value = new DataTransfer();
      value.items.add(new File([new Uint8Array(data)], filename, { type: 'application/pdf' }));
      return value;
    }, { filename: name, data: Array.from(bytes) });
    await page.locator('.student-dropzone').dispatchEvent('drop', { dataTransfer: transfer });
    await transfer.dispose();
  };
  await drop('invalid.txt', Buffer.from('invalid'));
  await expect(page.locator('.student-error')).toContainText('PDF');
  await drop('OOP.pdf', studentPdf(['Aggregation and composition describe object relationships in OOP.']));
  await expect(page.getByText('OOP.pdf', { exact: true })).toBeVisible();
  await expect.poll(async () => (await (await request.get(`/api/student/courses/${oop.id}/materials`)).json())[0]?.status).toBe('ready');
  const bytes = studentPdf(['SQL primary keys and foreign keys identify rows in database tables.']);
  const document = await (await request.post(`/api/student/courses/${db.id}/materials?filename=Database.pdf`, { headers: { 'Content-Type': 'application/pdf' }, data: bytes })).json();
  expect((await request.post(`/api/student/documents/${document.id}/process?sync=true`)).ok()).toBe(true);
  await page.getByRole('button', { name: 'Trò chuyện', exact: true }).click();
  const provider = page.locator('select[id^="chat-provider-"]'), mode = page.locator('select[id^="chat-mode-"]');
  await expect(provider).toHaveValue('ollama'); await expect(mode).toHaveValue('materials');
  await expect(page.getByRole('checkbox', { name: /Tìm trên web/ })).toBeDisabled();
  const question = page.locator('textarea[id^="chat-question-"]');
  await question.fill('Giải thích aggregation và composition');
  await page.getByRole('button', { name: 'Gửi', exact: true }).click();
  await expect(page.locator('.student-chat-assistant')).toHaveCount(1);
  await expect(page.locator('.student-chat-sources')).toContainText('OOP.pdf');
  await expect(page.locator('.student-chat-assistant')).not.toContainText('Database.pdf');
  await mode.selectOption('expanded');
  await question.fill('Explain outside the supplied file');
  await page.getByRole('button', { name: 'Gửi', exact: true }).click();
  await expect(page.locator('.student-chat-assistant')).toHaveCount(2);
  await expect(page.locator('.student-chat-assistant').last()).toContainText('Kiến thức chung');
  await expect(page.locator('.student-chat-assistant').last()).toContainText('Bổ sung từ kiến thức mô hình (chưa xác minh)');
  await expect(page.locator('.student-chat-assistant').last().locator('.student-chat-sources')).toHaveCount(0);
  await question.fill('Cancel this question');
  await page.getByRole('button', { name: 'Gửi', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Dừng trả lời', exact: true })).toBeVisible();
  await expect.poll(async () => (await (await request.get(`/api/student/courses/${oop.id}/chat`)).json()).turns.at(-1)?.phase).toBe('ai.respond');
  await page.getByRole('button', { name: 'Dừng trả lời', exact: true }).click();
  await expect(page.locator('.student-chat-failed')).toContainText('Đã dừng yêu cầu');
  await page.reload();
  const history = await (await request.get(`/api/student/courses/${oop.id}/chat`)).json();
  expect(history.turns.map((turn: { mode: string }) => turn.mode)).toEqual(['materials', 'expanded', 'expanded']);
  expect(history.turns.every((turn: { provider: string; isMock: boolean }) => turn.provider === 'ollama' && !turn.isMock)).toBe(true);
  expect((await (await request.get(`/api/student/courses/${db.id}/chat`)).json()).turns).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('local-chat-mobile.png'), fullPage: true });
  const office = await context.newPage();
  office.on('pageerror', (error) => errors.push(error.message));
  await office.goto('/?lang=vi&debug');
  await expect(office.locator('html')).toHaveAttribute('data-student-local', '1');
  await expect(office.locator('html')).not.toHaveAttribute('data-student-demo', '1');
  await expect(office.locator('#stage canvas')).toBeVisible({ timeout: officeStartTimeout });
  await expect(office.locator('#empty')).not.toContainText('No Claude');
  await office.locator('#demo-course-picker').selectOption(db.id);
  await expect(office.locator('.student-demo-open')).toHaveAttribute('href', new RegExp(db.id));
  await expect(office.getByRole('button', { name: 'Tạo dữ liệu mẫu', exact: true })).toHaveCount(0);
  await office.screenshot({ path: test.info().outputPath('local-office-desktop.png'), fullPage: true });
  await office.setViewportSize({ width: 390, height: 844 });
  expect(await office.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await office.screenshot({ path: test.info().outputPath('local-office-mobile.png'), fullPage: true });
  expect(external).toEqual([]); expect(errors).toEqual([]);
});
