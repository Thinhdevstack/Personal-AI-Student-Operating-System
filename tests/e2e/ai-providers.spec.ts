import { test, expect } from '@playwright/test';
import { studentPdf } from '../fixtures/student-pdf.mjs';

test('@smoke course chat selects three providers, persists attribution and retries the original provider', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const sent: { provider: string; requestId: string }[] = [];
  page.on('request', (req) => { if (req.method() === 'POST' && new URL(req.url()).pathname === '/api/student/chat') sent.push(req.postDataJSON()); });
  const semester = await (await request.post('/api/student/semesters', { data: { name: 'Provider semester', academicYear: '2026' } })).json();
  const course = await (await request.post('/api/student/courses', { data: { name: 'Provider OOP', semesterId: semester.id } })).json();
  const doc = await (await request.post(`/api/student/courses/${course.id}/materials?filename=Providers.pdf`, { headers: { 'Content-Type': 'application/pdf' }, data: studentPdf() })).json();
  expect((await request.post(`/api/student/documents/${doc.id}/process?sync=true`)).ok()).toBe(true);
  await page.goto(`/student?course=${course.id}&tab=chat`);
  const picker = page.getByLabel('AI provider', { exact: true });
  await expect(picker).toBeEnabled();
  await expect(picker.locator('option')).toHaveCount(3);
  await expect(page.getByText('Offline test mode', { exact: false })).toBeVisible();
  const send = async (provider: string, message: string) => {
    await picker.selectOption(provider);
    await page.getByLabel('Your question', { exact: true }).fill(message);
    await page.getByRole('button', { name: 'Send', exact: true }).click();
  };
  const answers = page.locator('.student-chat-assistant');
  await send('gemini', 'Explain aggregation');
  await expect(answers).toHaveCount(1);
  await expect(answers.first().locator('header')).toContainText('Google Gemini');
  await expect(answers.first()).toContainText('Providers.pdf');
  await page.route('**/api/student/chat', (route) => route.abort('failed'), { times: 1 });
  await send('deepseek', 'Explain composition');
  await expect(page.locator('.course-chat').getByRole('alert')).toBeVisible();
  await expect(picker).toBeDisabled();
  await page.getByRole('button', { name: 'Retry this question', exact: true }).click();
  await expect(answers).toHaveCount(2);
  await expect(answers.last().locator('header')).toContainText('DeepSeek');
  expect(sent[1].provider).toBe('deepseek'); expect(sent[2].provider).toBe('deepseek');
  expect(sent[1].requestId).toBe(sent[2].requestId);
  await send('openai', 'Give another example');
  await expect(answers).toHaveCount(3);
  await expect(answers.last().locator('header')).toContainText('OpenAI / ChatGPT');
  const history = await (await request.get(`/api/student/courses/${course.id}/chat`)).json();
  expect(history.turns.map((turn: { provider: string }) => turn.provider)).toEqual(['gemini', 'deepseek', 'openai']);
  await picker.selectOption('gemini');
  await page.reload();
  await expect(picker).toHaveValue('gemini');
  await expect(answers).toHaveCount(3);
  await page.locator('.student-provider-controls').scrollIntoViewIfNeeded();
  await page.screenshot({ path: test.info().outputPath('ai-providers-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/student?course=${course.id}&tab=chat&lang=vi`);
  await expect(page.getByLabel('Nhà cung cấp AI', { exact: true })).toHaveValue('gemini');
  await page.locator('.student-provider-controls').scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('ai-providers-mobile-vi.png'), fullPage: true });
  expect(errors).toEqual([]);
});
